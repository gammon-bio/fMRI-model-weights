"""Fine-tune a diagnosis head end-to-end on each pretrained checkpoint; evaluate the shortcut.

Usage: python scripts/finetune.py [--config configs/finetune.yaml] [--runs-dir outputs/runs]
                                  [--only confound_on:0 ...] [--jobs 1]
Writes results/finetune/<cond>_seed<k>.json, then results/finetune/summary.md and a figure.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from fmritest.config import apply_overrides, cap_threads, load_config  # noqa: E402

OUT = ROOT / "results" / "finetune"


def run_one(fcfg_path, runs_dir, cond, seed):
    fcfg = load_config(fcfg_path)
    base = load_config(ROOT / fcfg["base_config"])
    cfg = apply_overrides(base, base["conditions"][cond])
    cap_threads(cfg["compute"]["n_threads"])
    import numpy as np
    import torch
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import StratifiedKFold, cross_val_score
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler

    from fmritest.baselines.probes import site_probe
    from fmritest.data.generator import generate, zscore_subjects
    from fmritest.data.splits import make_splits
    from fmritest.eval.diagnosis import diag_eval
    from fmritest.finetune import evaluate, finetune, subject_embeddings
    from fmritest.models.transformer import build_model

    heldout = seed % cfg["data"]["n_sites"]
    ds = generate(cfg["data"], seed, heldout_site=heldout)
    X = zscore_subjects(ds.X)
    sp = make_splits(ds.site, heldout, tuple(cfg["split"]["frac"]), seed, group=ds.group, strata=ds.diagnosis)
    bb = build_model(cfg["model"], X.shape[2])
    bb.load_state_dict(torch.load(Path(runs_dir) / cond / f"seed{seed}" / "model.pt"))
    y, site = ds.diagnosis, ds.site
    res = {"condition": cond, "seed": seed, "heldout_site": int(heldout)}
    ck = ROOT / "outputs" / "finetune" / cond / f"seed{seed}"
    ck.mkdir(parents=True, exist_ok=True)
    for variant in ("vanilla", "reweight"):
        m, info = finetune(bb, X, y, site, sp["train"], fcfg["finetune"], seed, cfg["compute"]["n_threads"],
                           reweight=(variant == "reweight"))
        torch.save(m.state_dict(), ck / f"{variant}.pt")
        r = evaluate(m, X, y, sp)
        E = {k: subject_embeddings(m, X[v]) for k, v in sp.items()}
        r["site_probe"] = site_probe(E["train"], sp["train"], E["test"], sp["test"], site,
                                     C=1.0, n_perm=fcfg["eval"]["n_perm_probe"], seed=seed)
        # is real diagnosis signal present in the fine-tuned embedding? (single held-out site: no shortcut)
        ts = sp["test_site"]
        cv = StratifiedKFold(5, shuffle=True, random_state=seed)
        r["within_heldout_site_cv_bacc"] = float(cross_val_score(
            make_pipeline(StandardScaler(), LogisticRegression(C=0.1, max_iter=5000)), E["test_site"], y[ts],
            cv=cv, scoring="balanced_accuracy").mean())
        # post-hoc closed-form fixes on the fine-tuned embedding (fit on training subjects only)
        r["posthoc"] = {name: diag_eval(E, y, site, sp, 0.1, seed, reweight=rw, erase_site=er)
                        for name, rw, er in [("probe", False, False), ("probe+reweight", True, False),
                                             ("probe+leace_site", False, True),
                                             ("probe+leace_site+reweight", True, True)]}
        r["train_seconds"] = info["seconds"]
        r["loss_curve"] = info["curve"]
        res[variant] = r
        print(f"{cond} seed {seed} {variant}: bacc ID {r['test']['bacc']:.2f} balanced {r['test_balanced']['bacc']:.2f} "
              f"site {r['test_site']['bacc']:.2f} (auc {r['test_site']['auc']:.2f}) | site probe {r['site_probe']['acc']:.2f} "
              f"| within-site cv {r['within_heldout_site_cv_bacc']:.2f} | {info['seconds']:.0f}s", flush=True)
        print("   posthoc balanced/site bacc:", {k: (round(v["test_balanced"]["bacc"], 2), round(v["test_site"]["bacc"], 2))
                                                for k, v in r["posthoc"].items()}, flush=True)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{cond}_seed{seed}.json").write_text(json.dumps(res, indent=1))


def aggregate(fcfg):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    from scipy.stats import ttest_rel

    from fmritest.eval.metrics import mean_sd
    L = ["# Diagnosis fine-tuning (auto-generated by scripts/finetune.py)", "",
         "Backbone + linear head fine-tuned end-to-end on the planted diagnosis (training subjects, label "
         "correlated with site). `reweight` = same, with site x label importance weights (reference for an "
         "achievable non-shortcut model). Subject-level balanced accuracy (AUC); mean +/- SD over seeds.", ""]
    fig, axes = plt.subplots(1, len(fcfg["conditions"]), figsize=(6 * len(fcfg["conditions"]), 4), sharey=True)
    for ax, cond in zip(np.atleast_1d(axes), fcfg["conditions"]):
        rs = [json.loads((OUT / f"{cond}_seed{s}.json").read_text()) for s in fcfg["seeds"]]
        L += [f"## {cond}", "", "| variant | in-distribution | correlation broken | held-out site | site probe acc "
              "| within held-out site CV |", "|---|---|---|---|---|---|"]
        for v in ("vanilla", "reweight"):
            cell = lambda k: (f"{mean_sd([r[v][k]['bacc'] for r in rs])['mean']:.2f} +/- "
                              f"{mean_sd([r[v][k]['bacc'] for r in rs])['sd']:.2f} "
                              f"({np.mean([r[v][k]['auc'] for r in rs]):.2f})")
            sp_ = mean_sd([r[v]["site_probe"]["acc"] for r in rs])
            cv_ = mean_sd([r[v]["within_heldout_site_cv_bacc"] for r in rs])
            L.append(f"| {v} | {cell('test')} | {cell('test_balanced')} | {cell('test_site')} | "
                     f"{sp_['mean']:.2f} +/- {sp_['sd']:.2f} | {cv_['mean']:.2f} +/- {cv_['sd']:.2f} |")
        L += ["", "Post-hoc closed-form fixes on the fine-tuned (vanilla) embedding, fit on training subjects:", "",
              "| fix | in-distribution | correlation broken | held-out site |", "|---|---|---|---|"]
        for k in rs[0]["vanilla"]["posthoc"]:
            c2 = lambda d: (f"{np.mean([r['vanilla']['posthoc'][k][d]['bacc'] for r in rs]):.2f} +/- "
                            f"{np.std([r['vanilla']['posthoc'][k][d]['bacc'] for r in rs], ddof=1):.2f}")
            L.append(f"| {k} | {c2('test')} | {c2('test_balanced')} | {c2('test_site')} |")
        van = [r["vanilla"]["test_balanced"]["bacc"] for r in rs]
        rw = [r["reweight"]["test_balanced"]["bacc"] for r in rs]
        gap = [r["vanilla"]["shortcut_gap_bacc"] for r in rs]
        t_gap = ttest_rel([r["vanilla"]["test"]["bacc"] for r in rs], van, alternative="greater")
        t_head = ttest_rel(rw, van, alternative="greater")
        L += ["", f"Shortcut gap (vanilla, in-distribution minus correlation-broken): {np.mean(gap):.3f} +/- "
              f"{np.std(gap, ddof=1):.3f}, one-sided paired t p = {t_gap.pvalue:.2g}.",
              f"Repair headroom (reweight minus vanilla, correlation-broken bacc): {np.mean(np.subtract(rw, van)):.3f} "
              f"+/- {np.std(np.subtract(rw, van), ddof=1):.3f}, one-sided paired t p = {t_head.pvalue:.2g}, "
              f"reweight better in {int(np.sum(np.array(rw) > np.array(van)))}/{len(rs)} seeds.", ""]
        x = np.arange(3)
        for j, (v, c) in enumerate([("vanilla", "#E74C3C"), ("reweight", "#3498DB")]):
            vals = [[r[v][k]["bacc"] for r in rs] for k in ("test", "test_balanced", "test_site")]
            ax.bar(x + (j - 0.5) * 0.38, [np.mean(a) for a in vals], 0.38, yerr=[np.std(a, ddof=1) for a in vals],
                   color=c, capsize=3, label=v)
        ax.axhline(0.5, color="k", ls="--", lw=1)
        ax.set_xticks(x)
        ax.set_xticklabels(["in-distribution", "correlation broken", "held-out site"])
        ax.set_title(f"Fine-tuned diagnosis head ({cond})")
        ax.set_ylim(0.3, 1.05)
    np.atleast_1d(axes)[0].set_ylabel("subject-level balanced accuracy")
    np.atleast_1d(axes)[0].legend()
    fig.tight_layout()
    fig.savefig(OUT / "finetune_diagnosis.png", dpi=110)
    (OUT / "summary.md").write_text("\n".join(L))
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(ROOT / "configs" / "finetune.yaml"))
    ap.add_argument("--runs-dir", default=str(ROOT / "outputs" / "runs"))
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--jobs", type=int, default=1)
    ap.add_argument("--worker", nargs=2, metavar=("COND", "SEED"))
    ap.add_argument("--aggregate-only", action="store_true")
    a = ap.parse_args()
    fcfg = load_config(a.config)
    if a.worker:
        return run_one(a.config, a.runs_dir, a.worker[0], int(a.worker[1]))
    if not a.aggregate_only:
        jobs = [(c, s) for c in fcfg["conditions"] for s in fcfg["seeds"]]
        if a.only:
            jobs = [(c, int(s)) for c, s in (o.split(":") for o in a.only)]
        cmd = lambda c, s: [sys.executable, __file__, "--config", a.config, "--runs-dir", a.runs_dir, "--worker", c, str(s)]
        with ThreadPoolExecutor(a.jobs) as ex:
            rcs = list(ex.map(lambda j: subprocess.call(cmd(*j), cwd=ROOT), jobs))
        if any(rcs):
            sys.exit("fine-tune worker(s) failed")
        if a.only:
            return
    aggregate(fcfg)


if __name__ == "__main__":
    main()
