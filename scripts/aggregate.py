"""Aggregate per-run JSON into results/summary.{json,md} and draw figures in results/figures/."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from fmritest.baselines.fc import components_from_affinity  # noqa: E402
from fmritest.config import load_config  # noqa: E402
from fmritest.eval.metrics import mean_sd, network_recovery  # noqa: E402

RES, FIG = ROOT / "results", ROOT / "results" / "figures"
BLUE, RED, GREY = "#3498DB", "#E74C3C", "#7F8C8D"
plt.rcParams.update({"font.size": 11, "axes.spines.top": False, "axes.spines.right": False})


def load_runs(cfg):
    runs = {}
    for cond in cfg["conditions"]:
        rs = []
        for s in cfg["seeds"]:
            p = RES / "runs" / f"{cond}_seed{s}.json"
            if not p.exists():
                sys.exit(f"missing {p}; run `make runs` first")
            r = json.loads(p.read_text())
            r["curves"] = json.loads((RES / "runs" / f"{cond}_seed{s}_curves.json").read_text())
            rs.append(r)
        runs[cond] = rs
    return runs


RECON_KEYS = ("model", "fc", "fc_lag", "fc_site", "fc_site_lag", "best_linear", "zero", "untrained")
DIAG_SETS = ("test", "test_balanced", "test_site")


def summarise(rs):
    g = lambda f: mean_sd([f(r) for r in rs])
    out = {"recon": {}, "network": {}, "probe": {}, "leace_in_model": {}, "diagnosis": {}}
    for split in ("test", "test_site"):
        for k in RECON_KEYS:
            if k in rs[0]["recon"][split]:
                out["recon"][f"{split}/{k}"] = g(lambda r: r["recon"][split][k])
        out["recon"][f"{split}/model_minus_fc"] = g(lambda r: r["recon"][split]["model"] - r["recon"][split]["fc"])
        out["recon"][f"{split}/model_minus_best_linear"] = g(
            lambda r: r["recon"][split]["model"] - r["recon"][split]["best_linear"])
    for k, v in rs[0]["network"].items():
        if "score" not in v:
            continue
        out["network"][k] = g(lambda r: r["network"][k]["score"])
        out["network"][k + "/null_q95"] = g(lambda r: r["network"][k]["null_q95"])
        out["network"][k + "/p_perm"] = g(lambda r: r["network"][k]["p_perm"])
    out["network"]["untrained_mqa_null/max"] = g(lambda r: r["network"]["untrained_mqa_null"]["max"])
    for k in rs[0]["probe"]:
        for f in ("acc", "window_acc", "p_perm", "chance"):
            out["probe"][f"{k}/{f}"] = g(lambda r: r["probe"][k][f])
    for f in ("acc", "window_acc", "p_perm"):
        out["leace_in_model"][f"probe/{f}"] = g(lambda r: r["leace_in_model"]["probe"][f])
    for split in ("test", "test_site"):
        out["leace_in_model"][f"recon_{split}"] = g(lambda r: r["leace_in_model"][f"recon_{split}"])
        out["leace_in_model"][f"recon_{split}_delta_vs_model"] = g(
            lambda r: r["leace_in_model"][f"recon_{split}"] - r["recon"][split]["model"])
    if rs[0].get("diagnosis"):
        D = {k: v for k, v in rs[0]["diagnosis"].items() if not k.startswith("_")}
        if rs[0]["leace_in_model"].get("diagnosis"):
            for r in rs:
                r["diagnosis"]["model+leace_in_model"] = r["leace_in_model"]["diagnosis"]
            D["model+leace_in_model"] = None
        for k in D:
            for ds_ in DIAG_SETS:
                for f in ("bacc", "auc"):
                    out["diagnosis"][f"{k}/{ds_}/{f}"] = g(lambda r: r["diagnosis"][k][ds_][f])
    out["train_seconds"] = g(lambda r: r["train_seconds"])
    return out


def fmt(s, d=3):
    return f"{s['mean']:.{d}f} +/- {s['sd']:.{d}f}"


def write_md(summary, cfg):
    L = ["# Results summary (auto-generated by scripts/aggregate.py)", "",
         f"Mean +/- SD across seeds {cfg['seeds']}. Lower MSE is better. Synthetic data only.", ""]
    for cond, s in summary.items():
        L += [f"## Condition `{cond}` (overrides: {cfg['conditions'][cond] or 'none'})", "",
              "### Masked-region reconstruction MSE (z-scored units)", "",
              "| split | " + " | ".join(RECON_KEYS) + " | model - pooled FC | model - best linear |",
              "|---" * (len(RECON_KEYS) + 3) + "|"]
        for sp in ("test", "test_site"):
            r = s["recon"]
            L.append(f"| {sp} | " + " | ".join(fmt(r[f"{sp}/{k}"]) if f"{sp}/{k}" in r else "n/a" for k in RECON_KEYS)
                     + f" | {fmt(r[sp + '/model_minus_fc'])} | {fmt(r[sp + '/model_minus_best_linear'])} |")
        L += ["", "fc = pooled instantaneous FC; fc_lag = pooled with temporal context; fc_site* = per-site "
              "covariance (seen sites only). best_linear = per-seed minimum over the fc* baselines."]
        L += ["", "### Network recovery (Hungarian-matched mean |r| vs ground-truth membership)", "",
              "| readout | score | shuffled-label null q95 | max p_perm over seeds |", "|---|---|---|---|"]
        for k, v in s["network"].items():
            if "/" in k:
                continue
            L.append(f"| {k} | {fmt(v)} | {fmt(s['network'][k + '/null_q95'])} | "
                     f"{max(s['network'][k + '/p_perm']['values']):.3f} |")
        L += ["", f"Untrained-model null (per-seed max over random inits): {fmt(s['network']['untrained_mqa_null/max'])}.",
              "", "### Site decodability (held-out subjects of training sites; subject-level accuracy)", "",
              "| features | accuracy | window-level acc | chance | max p_perm over seeds |", "|---|---|---|---|---|"]
        pr = s["probe"]
        for k in sorted({k.split("/")[0] for k in pr}):
            L.append(f"| {k} | {fmt(pr[k + '/acc'])} | {fmt(pr[k + '/window_acc'])} | "
                     f"{pr[k + '/chance']['mean']:.3f} | {max(pr[k + '/p_perm']['values']):.3f} |")
        lm = s["leace_in_model"]
        L.append(f"| model + in-model LEACE | {fmt(lm['probe/acc'])} | {fmt(lm['probe/window_acc'])} | "
                 f"{pr['model/chance']['mean']:.3f} | {max(lm['probe/p_perm']['values']):.3f} |")
        L += ["", "In-model LEACE (token-level eraser on final residual stream, fit on training subjects): "
              f"reconstruction MSE change vs unedited model: test {fmt(lm['recon_test_delta_vs_model'], 4)}, "
              f"held-out site {fmt(lm['recon_test_site_delta_vs_model'], 4)}.", "",
              f"Training time per run: {fmt(s['train_seconds'], 0)} s.", ""]
        if s["diagnosis"]:
            names = sorted({k.split("/")[0] for k in s["diagnosis"]})
            L += ["### Planted diagnosis (shortcut task)", "",
                  "Probe fit on training subjects (diagnosis correlated with site). Balanced accuracy (AUC).", "",
                  "| features | in-distribution | correlation broken (test_balanced) | held-out site |", "|---|---|---|---|"]
            for n in names:
                d = s["diagnosis"]
                L.append(f"| {n} | " + " | ".join(
                    f"{fmt(d[f'{n}/{ds_}/bacc'], 2)} ({d[f'{n}/{ds_}/auc']['mean']:.2f})" for ds_ in DIAG_SETS) + " |")
            L.append("")
    (RES / "summary.md").write_text("\n".join(L))


def fig_curves(runs):
    fig, axes = plt.subplots(1, len(runs), figsize=(5.5 * len(runs), 4), sharey=True)
    for ax, (cond, rs) in zip(np.atleast_1d(axes), runs.items()):
        for r in rs:
            c = r["curves"]
            ax.plot(c["step"], c["train"], color=GREY, lw=1, alpha=0.7)
            ax.plot(c["step"], c["val"], color=BLUE, lw=1.2)
            ax.axhline(r["recon"]["test"]["fc"], color=RED, lw=0.8, ls="--")
        ax.set_title(f"{cond}: train (grey), val (blue)\nred dashed = FC baseline (test), per seed")
        ax.set_xlabel("step")
    np.atleast_1d(axes)[0].set_ylabel("masked MSE")
    fig.tight_layout()
    fig.savefig(FIG / "training_curves.png", dpi=110)
    plt.close(fig)


def _bars(ax, labels, vals, colors, null=None):
    m = [v["mean"] for v in vals]
    sd = [v["sd"] for v in vals]
    x = np.arange(len(labels))
    ax.bar(x, m, yerr=sd, color=colors, capsize=3)
    for i, v in enumerate(vals):
        ax.scatter(np.full(len(v["values"]), i) + np.linspace(-0.15, 0.15, len(v["values"])), v["values"],
                   s=10, color="k", zorder=3)
    if null is not None:
        ax.plot(x, [n["mean"] for n in null], "k_", ms=25, mew=2, label="shuffled-label null q95")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=30, ha="right")


def fig_network(summary, cond, suffix=""):
    s = summary[cond]["network"]
    keys = ["model_mqa_test", "model_mqa_test_site", "model_mqa_layer0", "model_mqa_layer1", "model_region_emb",
            "untrained_mqa_test", "fc_eig_varimax", "fc_pca", "fc_ica"]
    cols = [BLUE] * 5 + [GREY] + [RED] * 3
    fig, ax = plt.subplots(figsize=(8, 4.5))
    _bars(ax, keys, [s[k] for k in keys], cols, [s[k + "/null_q95"] for k in keys])
    ax.axhline(s["untrained_mqa_null/max"]["mean"], color=GREY, ls=":", lw=1.5, label="best of 10 untrained inits")
    ax.set_ylabel("Hungarian-matched mean |r|")
    ax.set_ylim(0, 1.05)
    ax.set_title(f"Network recovery ({cond})\nblue = trained model, grey = untrained, red = FC baselines", fontsize=11)
    ax.legend(loc="lower left", fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / f"network_recovery{suffix}.png", dpi=110)
    plt.close(fig)


def fig_site(summary):
    conds = list(summary)
    keys = ["model", "untrained", "fc", "model_leace_pooled"]
    fig, axes = plt.subplots(1, len(conds), figsize=(5 * len(conds), 4.2), sharey=True)
    for ax, cond in zip(np.atleast_1d(axes), conds):
        pr = summary[cond]["probe"]
        vals = [pr[k + "/acc"] for k in keys] + [summary[cond]["leace_in_model"]["probe/acc"]]
        _bars(ax, keys + ["model+LEACE(in-model)"], vals, [BLUE, GREY, RED, BLUE, BLUE])
        ax.axhline(pr["model/chance"]["mean"], color="k", ls="--", lw=1, label="chance")
        ax.set_title(f"Site probe, held-out subjects ({cond})")
        ax.set_ylim(0, 1.05)
    np.atleast_1d(axes)[0].set_ylabel("subject-level accuracy")
    np.atleast_1d(axes)[0].legend(fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / "site_decodability.png", dpi=110)
    plt.close(fig)


def fig_diagnosis(summary, cond):
    d = summary[cond]["diagnosis"]
    if not d:
        return
    names = [n for n in ["site_only", "fc", "fc+reweight", "untrained_token_concat", "model_pooled",
                         "model_token_concat", "model_token_concat+reweight", "model_token_concat+leace_site",
                         "model+leace_in_model", "model_attention", "model_attention+reweight"] if f"{n}/test/bacc" in d]
    fig, ax = plt.subplots(figsize=(13, 4.5))
    cols = {"test": GREY, "test_balanced": BLUE, "test_site": RED}
    w = 0.27
    for j, ds_ in enumerate(DIAG_SETS):
        v = [d[f"{n}/{ds_}/bacc"] for n in names]
        x = np.arange(len(names)) + (j - 1) * w
        ax.bar(x, [a["mean"] for a in v], w, yerr=[a["sd"] for a in v], color=cols[ds_], capsize=2,
               label={"test": "in-distribution (correlated)", "test_balanced": "correlation broken, seen sites",
                      "test_site": "held-out site"}[ds_])
    ax.axhline(0.5, color="k", ls="--", lw=1)
    ax.set_xticks(np.arange(len(names)))
    ax.set_xticklabels(names, rotation=25, ha="right", fontsize=9)
    ax.set_ylabel("balanced accuracy")
    ax.set_ylim(0.3, 1.05)
    ax.set_title(f"Planted-diagnosis shortcut ({cond}); mean +/- SD over seeds")
    ax.legend(fontsize=8, loc="upper right")
    fig.tight_layout()
    fig.savefig(FIG / "diagnosis_shortcut.png", dpi=110)
    plt.close(fig)


def fig_recon(runs):
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.2), sharey=True)
    for ax, split in zip(axes, ("test", "test_site")):
        xt = []
        for i, (cond, rs) in enumerate(runs.items()):
            for j, (k, c) in enumerate([("model", BLUE), ("best_linear", RED), ("zero", GREY)]):
                v = [r["recon"][split][k] for r in rs]
                x = i * 4 + j
                ax.bar(x, np.mean(v), yerr=np.std(v, ddof=1), color=c, capsize=3)
                ax.scatter(np.full(len(v), x), v, s=10, color="k", zorder=3)
                xt.append((x, f"{cond}\n{k}"))
            for r in rs:
                ax.plot([i * 4, i * 4 + 1], [r["recon"][split]["model"], r["recon"][split]["best_linear"]],
                        color="k", lw=0.5)
        ax.set_xticks([x for x, _ in xt])
        ax.set_xticklabels([t for _, t in xt], fontsize=8)
        ax.set_title({"test": "held-out subjects (training sites)", "test_site": "held-out site"}[split])
    axes[0].set_ylabel("masked-region MSE")
    fig.tight_layout()
    fig.savefig(FIG / "baseline_comparison.png", dpi=110)
    plt.close(fig)


def fig_example(cfg, cond):
    seed = cfg["seeds"][0]
    d = ROOT / "outputs" / "runs" / cond / f"seed{seed}"
    if not (d / "mqa_test.npy").exists():
        return
    A, M = np.load(d / "mqa_test.npy"), np.load(d / "membership.npy")
    C = components_from_affinity(A, M.shape[1], cfg["eval"]["network_extraction"])
    a = network_recovery(C, M)["assignment"]
    order = np.lexsort((-M.max(1), M.argmax(1)))
    fig, axes = plt.subplots(1, 3, figsize=(11, 4.5))
    axes[0].imshow(M[order], aspect="auto", cmap="magma")
    axes[0].set_title("ground-truth membership")
    axes[1].imshow(C[order][:, a], aspect="auto", cmap="magma")
    axes[1].set_title("recovered from model attention\n(Hungarian-ordered)")
    im = axes[2].imshow(A[np.ix_(order, order)], cmap="magma")
    axes[2].set_title("masked-query attention (regions sorted)")
    fig.colorbar(im, ax=axes[2], fraction=0.046)
    for ax in axes[:2]:
        ax.set_xlabel("network")
        ax.set_ylabel("region (sorted)")
    fig.suptitle(f"{cond}, seed {seed}")
    fig.tight_layout()
    fig.savefig(FIG / "example_networks.png", dpi=110)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(ROOT / "configs" / "default.yaml"))
    cfg = load_config(ap.parse_args().config)
    FIG.mkdir(parents=True, exist_ok=True)
    runs = load_runs(cfg)
    summary = {c: summarise(rs) for c, rs in runs.items()}
    (RES / "summary.json").write_text(json.dumps(summary, indent=1))
    write_md(summary, cfg)
    prim = cfg["gate"]["primary_condition"]
    fig_curves(runs)
    fig_network(summary, prim)
    if "hard" in summary:
        fig_network(summary, "hard", "_hard")
    fig_diagnosis(summary, prim)
    fig_site(summary)
    fig_recon(runs)
    fig_example(cfg, prim)
    print(f"wrote {RES / 'summary.md'} and figures in {FIG}")


if __name__ == "__main__":
    main()
